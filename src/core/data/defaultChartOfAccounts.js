const KIND_MAP = { Sintética: 'S', Analítica: 'A' }
const NATURE_MAP = { Devedora: 'D', Credora: 'C' }

function inferTypeFromCode(code) {
  return String(code || '').trim().startsWith('4') ? 'income' : 'expense'
}

function inferAllowPosting(code, kind) {
  return kind === 'A' && /^(4|5)(?:\.|$)/.test(String(code || '').trim())
}

export const defaultChartOfAccounts = RAW_CHART_ROWS.map(
  ([code, name, natureLabel, kindLabel, usageExample], index) => {
    const normalizedCode = String(code || '').trim()
    const kind = KIND_MAP[kindLabel] || 'A'
    const level = normalizedCode.split('.').filter(Boolean).length
    return {
      id: index + 1,
      code: normalizedCode,
      name: String(name || '').trim(),
      type: inferTypeFromCode(normalizedCode),
      kind,
      nature: NATURE_MAP[natureLabel] || 'C',
      level,
      parent_code: level > 1 ? normalizedCode.split('.').slice(0, -1).join('.') : null,
      allow_posting: inferAllowPosting(normalizedCode, kind),
      is_system: true,
      usage_example: String(usageExample || '').trim() || '',
    }
  },
).sort((a, b) => String(a.code).localeCompare(String(b.code), 'pt-BR', { numeric: true }))

